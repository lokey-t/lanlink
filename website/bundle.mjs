import { readFile, writeFile } from 'node:fs/promises';
const read = name => readFile(new URL(name, import.meta.url), 'utf8');
// A classic, self-contained script also works when index.html is opened via file://.
const parts = await Promise.all(['../vendor/qrcode.mjs', 'locales.js', 'downloads.js', 'app.js'].map(read));
const source = parts.map((part, index) => {
  part = part.replace(/^export default .*;\r?\n/gm, '').replace(/^export /gm, '').replace(/^import .* from .*;\r?\n/gm, '');
  if (index === 3) part = part.replace(/^import .* from .*;\r?\n/gm, '').replace("import('./downloads.js')", 'Promise.resolve({ setupDownloads })');
  return part;
}).join('\n');
await writeFile(new URL('app.bundle.js', import.meta.url), '// Generated by bundle.mjs; edit app.js, downloads.js and locales.js.\n(() => {\n' + source + '\n})();\n');
